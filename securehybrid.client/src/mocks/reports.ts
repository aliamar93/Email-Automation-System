import type { Report } from '../types'

// Naye report ka default SQL
export const DEFAULT_SQL = `SELECT
  wo.OrderID,
  wo.OrderDate,
  c.CustomerName,
  wo.WarehouseID,
  wo.Status,
  wo.TotalAmount,
  p.ProductName,
  p.Category
FROM dbo.WarehouseOrders wo
INNER JOIN dbo.Customers c ON wo.CustomerID = c.CustomerID
INNER JOIN dbo.Products p ON wo.ProductID = p.ProductID
WHERE wo.OrderDate >= @StartDate
    AND wo.OrderDate <= @EndDate
ORDER BY wo.OrderDate DESC`

// Report ke woh fields jo har report mein khud bhar jaate hain
